export const STUDIO_CC0_KRITA_RGBA_TIP_ALPHA_MAP_SIZE = 64;

export interface StudioCc0KritaRgbaTipImport {
  readonly tipId: string;
  readonly nameKo: string;
  /** Exact file inside RGBA_brushes.bundle (`brushes/` directory). */
  readonly upstreamFile: string;
  /** Documented single-channel reduction applied to the upstream image. */
  readonly reduction: "alpha-times-luma" | "inverted-luma";
  /** Base64 of 64×64 alpha bytes (standard alphabet, padded) — tip pipeline contract. */
  readonly alphaMapBase64: string;
  readonly alphaMapSize: number;
}

function tip(
  tipId: string,
  nameKo: string,
  upstreamFile: string,
  reduction: StudioCc0KritaRgbaTipImport["reduction"],
  alphaMapBase64: string,
): StudioCc0KritaRgbaTipImport {
  return Object.freeze({
    tipId,
    nameKo,
    upstreamFile,
    reduction,
    alphaMapBase64,
    alphaMapSize: STUDIO_CC0_KRITA_RGBA_TIP_ALPHA_MAP_SIZE,
  });
}

