/**
 * Ready-to-consume settings for the PNG-alpha tip pipeline. Shape "hard" only names the
 * procedural fallback slot — the custom alpha map overrides it whenever the payload validates,
 * and softness 0 keeps the imported texture unfiltered.
 */
export function resolveStudioCc0KritaRgbaTipSettings(
  tipId: string | null | undefined,
): StudioBrushTipSettings | null {
  const entry = resolveStudioCc0KritaRgbaTipImport(tipId);
  if (!entry) return null;
  if (entry.alphaMapSize > STUDIO_BRUSH_CUSTOM_TIP_ALPHA_MAP_MAX_SIZE) return null;
  return Object.freeze({
    shape: "hard",
    softness: 0,
    alphaMapBase64: entry.alphaMapBase64,
    alphaMapSize: entry.alphaMapSize,
  });
}
