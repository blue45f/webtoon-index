/**
 * CC0 Krita RGBA_brushes tip import v1 — real impasto/grain tip alpha maps.
 *
 * Upstream: `RGBA_brushes.bundle` by Ramon Miranda (2020-12), shipped with Krita. Provenance
 * chain: the bundle's meta.xml declares license "Same as default brushes in Krita" and the Krita 4
 * default resources bundle (`Krita_4_Default_Resources.bundle`) meta.xml declares license="CC-0",
 * so these tip images are CC0 by reference. We archive both meta.xml statements here verbatim.
 *
 * Reduction formula (documented honesty — these are ALPHA REDUCTIONS of RGBA tips, not the full
 * RGBA/lightness impasto payloads):
 * - RGBA sources (`Craig_02.png`, `Mountain_Brush_01.png`): coverage = alpha01 × luma01
 *   (Rec. 709 luma). RGB carries bristle-height detail in the RGBA brush model; multiplying it
 *   into coverage keeps the groove texture in a single channel.
 * - Grayscale source (`DA_Triangle grain.png`, white background): coverage = 1 − luma01.
 * - Non-square sources are centre-padded to square (aspect preserved), box-downsampled to 64×64
 *   (the in-document custom tip cap, studio-brush-tip-stamp), then max-normalized to the 0..255
 *   byte range.
 *
 * The payloads are plain `StudioBrushTipSettings`-shaped custom alpha maps, so the dynamic-dabs
 * tip pipeline (`buildStudioBrushTipAlphaMap` / `planStudioBrushTipStamp`) consumes them without
 * any new code path. Static data only — determinism is trivial.
 */

